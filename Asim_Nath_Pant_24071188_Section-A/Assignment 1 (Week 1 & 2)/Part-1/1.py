'''
1. Program to print the perimeter of a rectangle with length 9 and width 6

'''

# Initializing the length and width of rectangle
length = 9
width = 6

# Calculating the perimeter of rectangle
perimeter = 2 * (length + width)

# Displaying the perimeter of rectangle to the user
print("The perimeter of a rectangle with length 9 and width 6 is", perimeter, "respectively.")
