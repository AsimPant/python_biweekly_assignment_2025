'''
3. Write a program that will convert Celsius value to Fahrenheit.

'''

# Asking the user to enter the temperature in Celsius
celsius = float(input("Enter the temperatture in Celsius: "))

# Calculating the entered Celsius temperature in Fahrenheit
fahrenheit = celsius * (9 / 5) + 32

# Displaying the Fahrenheit temperature to the user
print("\nThe temperature in Fahrenheit scale is", fahrenheit, "respectively.")
